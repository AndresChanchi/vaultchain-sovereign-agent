//! # Fallback Dispatcher
//!
//! Single `#[fallback]` entrypoint that routes raw calldata to per-method
//! `dispatch_*` handlers.
//!
//! WHY FALLBACK INSTEAD OF `#[public]`:
//!
//! The Stylus SDK's `#[public]` attribute expands into one monolithic
//! `route()` function that inlines the ABI decode of every method's
//! arguments and the ABI encode of every method's return value. With
//! 48 methods — several of them heavy (`register_batch` with six `Vec`
//! arguments, `get_metadata` with an 8-tuple return,
//! `verify_identity_authorization` with two `Vec`s plus cross-contract
//! calls) — the generated `route()` exceeded the ArbOS 65,536-opcode
//! limit per function, causing activation to fail with
//! `too many wasm opcodes in func body`.
//!
//! The fallback approach moves every decode and encode step into a
//! dedicated function. The dispatcher itself becomes a tiny `match`
//! over selectors that only emits `call` instructions, and every
//! `dispatch_*` handler gets its own 65,536-opcode budget.
//!
//! WHY THE DISPATCH IS INDIRECT (`call_indirect`) AND NOT A `match`:
//!
//! A plain `match` in `fallback` is not enough. The Stylus build
//! pipeline runs `wasm-opt -Oz --converge --closed-world` over the
//! output of LLVM. Binaryen has its own inliner that is independent of
//! LLVM and does **not** honor Rust's `#[inline(never)]`: the attribute
//! is a hint to LLVM IR that is lost in the translation to WASM.
//! Because the entrypoint is the only exported function of the module,
//! Binaryen's pipeline sees every `dispatch_*` as having a single call
//! site and inlines all of them into `user_entrypoint`, rebuilding the
//! monolithic body the fallback split was designed to avoid.
//!
//! Measured evidence (wasm-objdump -d over the post-`wasm-opt` binary):
//!   - Before the fix: `user_entrypoint` had 46787 ops → ArbOS read
//!     94164 (2x factor for structured ops), above the 65536 limit.
//!   - Same pattern is visible in `kipio_account` at 19840 ops, which
//!     passes because it is smaller.
//!
//! Routing through a table of function pointers produces a
//! `call_indirect` in WASM. Binaryen cannot inline through
//! `call_indirect` because the target is a runtime value loaded from a
//! table, not a statically known function index. This preserves the
//! per-handler opcode budget that the ArbOS limit requires.
//!
//! `core::hint::black_box` on the table reference prevents LLVM from
//! devirtualizing the lookup back into a static `match` during codegen.
//! Without it, LLVM's own constant propagation would defeat the entire
//! purpose before Binaryen even runs.
//!
//! HANDLER SIGNATURE AND MUTABILITY:
//!
//! Every dispatch handler takes `&mut KipioIdentityContent`, including
//! the ones whose body only reads storage. The uniform signature is
//! required so the handlers can be stored in a single `DispatchHandler`
//! fn-pointer table. Read-only handlers simply do not write anything;
//! the `&mut` borrow is a formality that costs nothing at the WASM
//! level. Making all handlers accept `&mut self` also matches the
//! shape of `#[fallback]`, whose receiver is `&mut self`, so the
//! table call is a direct pass-through with no bridging.
//!
//! CONSTRUCTOR:
//!
//! `#[constructor]` stays inside the same `#[public]` block as the
//! fallback. The SDK's generated dispatcher handles the constructor
//! selector directly (its decode is trivial: three `address` + one
//! `bytes32`), and forwards every other selector to `fallback`.
//!
//! SELECTOR CONVENTION:
//!
//! Selectors follow Solidity's camelCase convention. Each function is
//! declared once in the `sol!` block below; its `[u8; 4]` selector is
//! derived at compile time via `SolCall::SELECTOR`. The `u32`
//! constants are what the dispatcher compares against.
//!
//! ABI DECODING:
//!
//! `SolCall::abi_decode` is used for every handler. It returns the typed
//! call struct whose fields already have the correct Rust types:
//!
//!   - Solidity `uint8`  → `u8`
//!   - Solidity `uint16` → `u16`
//!   - Solidity `uint32` → `u32`
//!   - Solidity `uint64` → `u64`
//!   - Solidity `uint256` → `U256`
//!   - Solidity `bytes`  → `stylus_sdk::abi::Bytes`
//!   - Solidity `T[]`    → `alloc::vec::Vec<T>`
//!
//! ABI ENCODING:
//!
//! Return values are encoded with `SolCall::abi_encode_returns_tuple`,
//! which operates on the function's declared return tuple
//! (`Self::ReturnTuple`) through the `SolTypeValue` trait. This is the
//! same code path the `#[public]` macro uses internally and it handles
//! `u8` fields (`uint8`) without requiring `u8: SolValue` (a bound that
//! Rust's coherence rules forbid us from satisfying).
//!
//! `abi_encode_returns` (without the `_tuple` suffix) is not used
//! because it expects `&Self::Return`, and `Self::Return` is a named
//! struct generated by the `sol!` macro (e.g. `getMetadataReturn`),
//! not the plain Rust tuple.
//!
//! For single-value returns that do not involve `u8`, the simpler
//! `SolValue::abi_encode_params` with a one-element tuple still works:
//! `(value,).abi_encode_params()`.
//!
//! DECODE HELPERS:
//!
//! `SolCall::abi_decode` is not free: expanding the decoder for a
//! dynamic argument (`bytes`, `T[]`) produces a non-trivial sequence of
//! offset reads, bounds checks and length resolution. Extracting them
//! into free, `#[inline(never)]` functions keeps each dispatch body to
//! a single `call` at the source level. Note that `#[inline(never)]`
//! alone is not sufficient (Binaryen ignores it); the decode helpers
//! are complements to the indirect dispatch, not substitutes.
//!
//! BYTES HANDLING:
//!
//! `stylus_sdk::abi::Bytes` is a newtype over `alloy_primitives::Bytes`.
//! It implements `Deref<Target = [u8]>`, so it can be used directly
//! wherever a `&[u8]` is expected (indexing, `len()`, `is_empty()`,
//! `extend_from_slice`). When an owned `Vec<u8>` is required (e.g.
//! passing a `bytes` argument to `call_verifier`, whose signature takes
//! `Vec<u8>`), the inner `alloy_primitives::Bytes` is converted with
//! `.to_vec()`.
//!
//! TRADE-OFF:
//!
//! `#[public]` also auto-generates a `GenerateAbi` impl used by the
//! `export-abi` binary. With fallback-only that impl disappears; the
//! Solidity interface must be maintained separately. The ABI surface
//! itself is unchanged: every selector below matches the pre-refactor
//! `cargo stylus export-abi` output byte for byte.

