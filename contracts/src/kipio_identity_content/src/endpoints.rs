// ============================================================================
// PUBLIC INTERFACE — CONSTRUCTOR + FALLBACK
// ============================================================================

#[public]
impl KipioIdentityContent {
    #[constructor]
    pub fn constructor(
        &mut self,
        storage_provider: Address,
        query_provider: Address,
        access_provider: Address,
        expected_workflow_id: B256,
    ) -> Result<(), Vec<u8>> {
        let deployer = self.vm().tx_origin();
        if deployer == Address::ZERO {
            return Err(ZeroOwner {}.abi_encode());
        }
        self.owner.set(deployer);
        self.storage_provider.set(storage_provider);
        self.query_provider.set(query_provider);
        self.access_provider.set(access_provider);
        self.expected_workflow_id.set(expected_workflow_id);
        self.initialized.set(true);
        Ok(())
    }

    /// @notice Entry point for every non-constructor call.
    ///
    /// @dev Reads the 4-byte selector from `calldata`, resolves the
    ///      handler through `DISPATCH_TABLE` (indirect call, opaque to
    ///      `wasm-opt`'s inliner), and forwards the argument slice.
    ///      See the module-level documentation for the full rationale.
    #[fallback]
    fn fallback(&mut self, calldata: &[u8]) -> ArbResult {
        if calldata.len() < 4 {
            return Err(Vec::new());
        }
        let selector = u32::from_be_bytes([calldata[0], calldata[1], calldata[2], calldata[3]]);
        let args = &calldata[4..];

        // `black_box` on the table reference prevents LLVM from
        // constant-folding the linear scan into a static decision tree.
        // The subsequent `call_indirect` is what keeps `wasm-opt` from
        // inlining every handler into the entrypoint.
        let table: &[(u32, DispatchHandler)] = black_box(DISPATCH_TABLE);

        let mut handler: Option<DispatchHandler> = None;
        for &(sel, h) in table.iter() {
            if sel == selector {
                handler = Some(h);
                break;
            }
        }

        match handler {
            Some(h) => h(self, args),
            None => Err(Vec::new()),
        }
    }
}

// ============================================================================
// DISPATCH HANDLERS
// ============================================================================
//
// Each handler performs its own ABI decode, executes the original method
// body, and ABI-encodes the return value. All handlers take `&mut self`
// so they share a single `DispatchHandler` fn-pointer type.
//
// At the source level they carry `#[inline(never)]`. At the WASM level
// this attribute has no effect (Binaryen does not honor it), which is
// why the dispatcher routes through an indirect call. Both mechanisms
// together keep every reachable function under the ArbOS 65,536
// opcode-per-body limit.
//
// Decoders for dynamic argument lists live in the `decode_*` helpers at
// module scope (see above). Decoders for fixed-size argument lists stay
// inline in the handler because their expansion is small.

