    #[inline(never)]
    fn dispatch_get_metadata(&mut self, args: &[u8]) -> ArbResult {
        let call = getMetadataCall::abi_decode(args).map_err(|_| Vec::new())?;
        let vault = self.vaults.getter(call.owner);
        let record = vault.contents.getter(call.content_id);
        let packed = record.packed.get();
        if packed == U256::ZERO {
            return Err(NotFound {}.abi_encode());
        }
        let (version, created_at, updated_at, provider_id, is_public, storage_term, expiry_delta) =
            unpack_metadata(packed);
        let absolute_expiry = compute_absolute_expiry(created_at, expiry_delta);

        // `abi_encode_returns_tuple` accepts the raw Rust-type tuple
        // directly. It goes through `SolTypeValue<Self::ReturnTuple>`
        // instead of `SolValue`, so `u8` fields (`uint8` in Solidity)
        // are handled without requiring `u8: SolValue` — a bound that
        // Rust's coherence rules forbid us from satisfying.
        //
        // `abi_encode_returns` (without the `_tuple` suffix) is not used
        // because it expects `&Self::Return`, and `Self::Return` is the
        // named struct generated by the `sol!` macro
        // (`getMetadataReturn`), not the plain tuple.
        Ok(getMetadataCall::abi_encode_returns_tuple(&(
            version,
            created_at,
            updated_at,
            provider_id,
            is_public,
            storage_term,
            expiry_delta,
            absolute_expiry,
        )))
    }

