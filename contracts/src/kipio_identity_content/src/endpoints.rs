// ============================================================================
// DISPATCH TABLE — INDIRECT DISPATCH
// ============================================================================
//
// The fallback routes through this table instead of a `match`. The
// lookup produces a `call_indirect` in WASM, which `wasm-opt` cannot
// inline (the target is a runtime value loaded from a table, not a
// statically known function index). This is what preserves the
// per-handler opcode budget that the ArbOS 65,536 limit requires.
//
// `core::hint::black_box` on the table reference prevents LLVM from
// constant-folding the lookup back into a direct call during codegen.
// Without it, LLVM's own devirtualization would defeat the entire
// purpose before `wasm-opt` even runs.
//
// Handler signature:
//
//     fn(&mut KipioIdentityContent, &[u8]) -> ArbResult
//
// All handlers accept `&mut self`, including read-only ones. See the
// module-level documentation for the rationale.
//
// LOOKUP STRATEGY:
//
// Linear scan over an unsorted table. At 48 entries the cost is
// negligible (the JIT compiles this to a tight loop with early exit),
// and it avoids the maintenance hazard of keeping the table sorted by
// selector value — which would require re-deriving every constant on
// every addition and is a subtle source of bugs. Since the table is
// passed through `black_box`, LLVM cannot unroll the loop into a
// static decision tree even though the entries are compile-time
// constants.

type DispatchHandler = fn(&mut KipioIdentityContent, &[u8]) -> ArbResult;

