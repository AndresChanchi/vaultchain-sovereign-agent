// ============================================================================
// DECODE HELPERS
// ============================================================================
//
// Every decoder whose argument list contains a dynamic type (`bytes`,
// `T[]`) lives here as a free, `#[inline(never)]` function.
//
// WHY:
//
// `SolCall::abi_decode` for a dynamic argument expands into a
// non-trivial sequence of offset reads, bounds checks and length
// resolution. Extracting them into dedicated functions keeps each
// dispatch body to a single `call` at the source level, which
// complements the indirect dispatch in bounding the total opcode
// count of every reachable WASM function.
//
// WHAT IS NOT HERE:
//
// Decoders for fixed-size argument lists (`address`, `bytes32`, `bool`,
// `uint8..uint64`) stay inline inside their dispatch handler because
// their expansion is small and the extra `call` overhead would
// dominate.

/// @dev Decodes `registerBatch(bytes32[],bytes32[],uint8[],bytes32[],uint8[],uint32[])`.
///      Six dynamic arrays; the heaviest decoder in the contract.
#[inline(never)]
fn decode_register_batch(args: &[u8]) -> Result<registerBatchCall, Vec<u8>> {
    registerBatchCall::abi_decode(args).map_err(|_| Vec::new())
}

